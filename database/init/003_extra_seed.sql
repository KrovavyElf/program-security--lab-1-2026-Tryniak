-- ---------- Генерація місць для всіх нових залів + добудова місць для залів №2 і №3
-- CineVerse Central, яким їх бракувало ще з 002_seed.sql (там місця згенеровано
-- тільки для залу №1 IMAX). Останні 2 ряди в не-STANDARD залах позначені як VIP.
DO $$
DECLARE
    hall RECORD;
    r INT;
    s INT;
    seat_type VARCHAR(20);
BEGIN
    FOR hall IN
        SELECT * FROM (VALUES
            ('d0000000-0000-0000-0000-000000000002'::UUID, 8, 10, FALSE),  -- CineVerse Central, зал №2 Standard
            ('d0000000-0000-0000-0000-000000000003'::UUID, 5, 8,  TRUE),   -- CineVerse Central, зал №3 VIP
            ('d0000000-0000-0000-0000-000000000004'::UUID, 10, 12, FALSE), -- Kyiv IMAX
            ('d0000000-0000-0000-0000-000000000005'::UUID, 8, 10, FALSE),  -- Kyiv Standard
            ('d0000000-0000-0000-0000-000000000006'::UUID, 6, 8,  TRUE),   -- Kyiv 4DX
            ('d0000000-0000-0000-0000-000000000007'::UUID, 8, 10, FALSE),  -- Dnipro Standard
            ('d0000000-0000-0000-0000-000000000008'::UUID, 5, 8,  TRUE),   -- Dnipro VIP
            ('d0000000-0000-0000-0000-000000000009'::UUID, 8, 10, FALSE),  -- Dnipro 3D
            ('d0000000-0000-0000-0000-000000000010'::UUID, 8, 10, FALSE),  -- Lviv Standard
            ('d0000000-0000-0000-0000-000000000011'::UUID, 10, 12, FALSE)  -- Lviv IMAX
        ) AS t(hall_id, rows_count, seats_per_row, mark_vip)
    LOOP
        FOR r IN 1..hall.rows_count LOOP
            FOR s IN 1..hall.seats_per_row LOOP
                seat_type := 'STANDARD';
                IF r = 1 AND s <= 2 THEN
                    seat_type := 'DISABLED';
                ELSIF hall.mark_vip AND r >= hall.rows_count - 1 THEN
                    seat_type := 'VIP';
                END IF;

                INSERT INTO "Seats" ("HallId", "RowNumber", "SeatNumber", "Type")
                VALUES (hall.hall_id, r, s, seat_type);
            END LOOP;
        END LOOP;
    END LOOP;
END $$;

