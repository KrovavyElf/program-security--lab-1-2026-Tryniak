-- Для кожного з 30 залів мережі на кожен робочий день (Пн–Пт) протягом
-- наступних 2 місяців генеруємо сеанси фільмів у прокаті ('NOW_SHOWING')
-- впритул один за одним з 10:00 до 22:00, з перервою 30 хв між сеансами
-- (на прибирання залу) — так, щоб зал був завантажений максимально повно.
DO $$
DECLARE
    hall_rec       RECORD;
    movie_ids      UUID[];
    movie_durations INT[];
    movie_count    INT;
    session_format VARCHAR(20);
    session_price  DECIMAL(10,2);
    hall_idx       INT := 0;
    cur_date       DATE;
    end_date       DATE;
    day_idx        INT;
    slot_idx       INT;
    cursor_time    TIMESTAMPTZ;
    day_end        TIMESTAMPTZ;
    mv_pos         INT;
    mv_id          UUID;
    mv_duration    INT;
    sess_end       TIMESTAMPTZ;
BEGIN
    -- Стабільний (за назвою) список фільмів, що йдуть в прокаті зараз
    SELECT array_agg("Id" ORDER BY "Title"), array_agg("Duration" ORDER BY "Title")
      INTO movie_ids, movie_durations
      FROM "Movies"
      WHERE "Status" = 'NOW_SHOWING';
    movie_count := array_length(movie_ids, 1);

    end_date := CURRENT_DATE + INTERVAL '2 months';

    FOR hall_rec IN SELECT "Id", "Type" FROM "Halls" ORDER BY "Id" LOOP
        hall_idx := hall_idx + 1;

        session_format := CASE hall_rec."Type"
            WHEN 'IMAX'    THEN 'IMAX'
            WHEN 'VIP'     THEN 'VIP'
            WHEN 'FOUR_DX' THEN '4DX'
            WHEN 'THREE_D' THEN '3D'
            ELSE '2D'
        END;
        session_price := CASE hall_rec."Type"
            WHEN 'IMAX'    THEN 260.00
            WHEN 'VIP'     THEN 360.00
            WHEN 'FOUR_DX' THEN 310.00
            WHEN 'THREE_D' THEN 240.00
            ELSE 170.00
        END;

        day_idx  := 0;
        cur_date := CURRENT_DATE;
        WHILE cur_date < end_date LOOP
            -- ISODOW: Пн=1 ... Нд=7 — беремо лише робочі дні Пн–Пт
            IF EXTRACT(ISODOW FROM cur_date) BETWEEN 1 AND 5 THEN
                cursor_time := cur_date + TIME '10:00';
                day_end     := cur_date + TIME '22:00';
                slot_idx    := 0;

                LOOP
                    mv_pos      := ((hall_idx + day_idx + slot_idx) % movie_count) + 1;
                    mv_id       := movie_ids[mv_pos];
                    mv_duration := movie_durations[mv_pos];
                    sess_end    := cursor_time + (mv_duration || ' minutes')::INTERVAL;

                    EXIT WHEN sess_end > day_end;

                    INSERT INTO "Sessions" ("MovieId", "HallId", "StartTime", "EndTime", "Format", "BasePrice")
                    VALUES (mv_id, hall_rec."Id", cursor_time, sess_end, session_format, session_price);

                    cursor_time := sess_end + INTERVAL '30 minutes';
                    slot_idx    := slot_idx + 1;
                END LOOP;

                day_idx := day_idx + 1;
            END IF;

            cur_date := cur_date + INTERVAL '1 day';
        END LOOP;
    END LOOP;
END $$;

